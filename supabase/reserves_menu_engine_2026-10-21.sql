create temp table matched on commit drop as
  select m.*, c.id as customer_id, canonical_strain(m.strain) as canon
    from me_reserves m left join customers c on lower(c.name) = lower(m.customer);

do $$
declare bad text;
begin
  select string_agg(distinct coalesce(case when customer_id is null then 'customer ' || customer end, 'strain ' || strain), ', ') into bad
    from matched where customer_id is null or canon is null;
  if bad is not null then raise exception 'Not found: %', bad; end if;
end $$;

insert into reserves (customer_id, strain, lbs, notes, created_by, updated_by)
select customer_id, canon, sum(lbs), 'From menu engine', 'aziz@lifted-organics.com', 'aziz@lifted-organics.com'
  from matched group by customer_id, canon
on conflict (customer_id, lower(strain), product) do update set lbs = excluded.lbs, updated_by = excluded.updated_by, updated_at = now();

insert into events (user_email, type, note, details)
select 'aziz@lifted-organics.com', 'reserve_import', 'Menu engine v03.01',
       jsonb_build_object('rows', count(*), 'lbs', sum(lbs), 'customers', count(distinct customer_id)) from matched;

