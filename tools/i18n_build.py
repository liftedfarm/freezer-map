"""Builds src/i18n.es.ts from tools/i18n_es.tsv (English<TAB>Spanish) and lists any t('...') text with no Spanish yet.
Run from the repo root: python3 tools/i18n_build.py"""
import glob, json, re
ES, EN = {}, {}
for line in open('tools/i18n_es.tsv', encoding='utf-8'):
    if line.startswith('#') or '\t' not in line: continue
    en, es = line.rstrip('\n').split('\t', 1)
    if es.strip(): ES[en] = es
# long texts keyed by a short id: their English lives here too
EN['PLAN_HOWTO_1'] = "Works back from the clone orders for {year} (Production's nursery deliveries and outside orders): G4 cuttings = order + {buffer}% in trays of {tray}. G3 field moms = G4 cuttings ÷ {g3} cuts per mom. Each generation above is cut with +{buffer}% and G2 at {g2} cuts per mom."
EN['PLAN_HOWTO_2'] = "Cut-by dates: G4 = first delivery − {root} days, G3 planted {veg} days before that and cut {g3root} days before planting, G2 {g2} days before G3, G1 {g1} days before G2."
EN['PLAN_HOWTO_3'] = '"Have" counts live mother lots for the season; +N is rooting now. Each generation only needs to cover what the one below is still short. Tap a strain to change its cuts per mom.'
used = set()
for f in glob.glob('src/**/*.ts*', recursive=True):
    if f.endswith('i18n.es.ts'): continue
    s = open(f, encoding='utf-8').read()
    for m in re.finditer(r"\bt\(\s*'((?:[^'\\]|\\.)*)'", s): used.add(m.group(1).replace("\\'", "'"))
    for m in re.finditer(r"\btn\([^,]+,\s*'((?:[^'\\]|\\.)*)',\s*'((?:[^'\\]|\\.)*)'", s): used |= {m.group(1).replace("\\'", "'"), m.group(2).replace("\\'", "'")}
missing = sorted(k for k in used if k not in ES and re.search('[A-Za-z]{2}', k) and k not in ('English text', '+ ', 'No '))
out = ['// Generated by tools/i18n_build.py from tools/i18n_es.tsv. Edit the .tsv, not this file.',
       'export const ES: Record<string, string> = ' + json.dumps(ES, ensure_ascii=False, indent=1),
       'export const EN: Record<string, string> = ' + json.dumps(EN, ensure_ascii=False, indent=1), '']
open('src/i18n.es.ts', 'w', encoding='utf-8').write('\n'.join(out))
print(f'{len(ES)} Spanish entries; {len(missing)} used without Spanish:')
for k in missing: print('  ', k)
