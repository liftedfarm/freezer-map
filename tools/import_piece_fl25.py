"""Builds supabase/import_piece_fl25.sql from the FL25 Bucking & Trimming Piece Rate workbook.
   python3 tools/import_piece_fl25.py "FL25 Bucking  Trimming Piece Rate.xlsx"
Reads the daily blocks on the Dry Bucking and Trimming tabs (one row per person, per day, per lot) and the crew on the Lists tab.
Coastal Sun rows are skipped (Aziz: disregard Coastal). The pay periods they fall in are closed and marked paid."""
import datetime, re, sys
import openpyxl

def q(s): return 'null' if s is None else "'" + str(s).replace("'", "''") + "'"
def n(x):
    try: return float(x or 0)
    except (TypeError, ValueError): return 0.0

wb = openpyxl.load_workbook(sys.argv[1], data_only=True)
crew = set()
ws = wb['Lists']
for r in range(3, ws.max_row + 1):
    f, l = ws.cell(r, 2).value, ws.cell(r, 3).value
    if f and l and '[' not in str(f): crew.add(f'{str(f).strip()} {str(l).strip()}')
rows = []
for sheet, task in [('Dry Bucking', 'buck'), ('Trimming', 'trim')]:
    ws = wb[sheet]
    for s in [c.column for c in ws[8] if c.value == '# Equipo']:
        hdr, day = None, None
        for r in range(1, ws.max_row + 1):
            v = ws.cell(r, s).value
            if v == 'Fecha': day = ws.cell(r, s + 1).value; continue
            if v == '# Equipo': hdr = [(ws.cell(r, s + i).value or '') for i in range(16)]; continue
            name = ws.cell(r, s + 1).value
            if not hdr or not isinstance(name, str) or not name.strip() or not isinstance(day, datetime.datetime): continue
            x = {re.sub(r'\s+', ' ', str(h)).strip(): ws.cell(r, s + i).value for i, h in enumerate(hdr) if h}
            m = re.match(r'.*\(FL(\d\d)(OH|GV)\)\s*-\s*(.+)$', str(x.get('Variedad') or ''))
            if not m: continue   # summary rows, Coastal Sun, blank lots
            lbs, hours = n(x.get('Total Libras')), n(x.get('Total Horas'))
            if lbs <= 0 and hours <= 0: continue
            rows.append((day.date().isoformat(), name.strip(), task, m.group(3).strip(), 2000 + int(m.group(1)), 'OHR' if m.group(2) == 'OH' else 'GVR',
                         lbs, n(x.get('Total Moho')), n(x.get('Total Small') or x.get('Total Smalls')), n(x.get('Total Trim')), hours))
            crew.add(name.strip())

out = ['-- Generated by tools/import_piece_fl25.py from the FL25 Bucking & Trimming Piece Rate workbook. Run after 048_piece_rate.sql. Safe to re-run.',
       f'-- {len(rows)} piece entries ({sum(1 for r in rows if r[2] == "buck")} bucking, {sum(1 for r in rows if r[2] == "trim")} trimming), {len(crew)} crew.',
       'begin;',
       'insert into employees (name, created_by) values ' + ',\n  '.join(f"({q(c)}, 'FL25 workbook')" for c in sorted(crew)) + '\non conflict do nothing;',
       '-- start over on anything imported before (reopen its periods first so the entries can be replaced)',
       "update pay_periods set status = 'open' where status = 'closed' and closed_by = 'FL25 workbook';",
       "delete from piece_entries where source = 'FL25 workbook';",
       'insert into piece_entries (work_date, employee_id, task, strain, crop_year, farm, lbs, mold, smalls, trim, hours, source, entered_by)',
       'select v.d::date, e.id, v.t, coalesce(canonical_strain(v.s), v.s), v.y, v.f, v.l, v.m, v.sm, v.tr, v.h, \'FL25 workbook\', \'FL25 workbook\' from (values']
out.append(',\n'.join(f'  ({q(r[0])}, {q(r[1])}, {q(r[2])}, {q(r[3])}, {r[4]}, {q(r[5])}, {r[6]:.2f}, {r[7]:.2f}, {r[8]:.2f}, {r[9]:.2f}, {r[10]:.2f})' for r in rows))
out += [') v(d, n, t, s, y, f, l, m, sm, tr, h) join employees e on lower(e.name) = lower(v.n);',
        '-- the periods these fall in were paid from the workbook: close them and mark them sent to payroll',
        'do $$',
        'declare s date; p pay_periods;',
        'begin',
        "  for s in select distinct pay_period_start(work_date) from piece_entries where source = 'FL25 workbook' loop",
        '    p := pay_period_for(s);',
        "    if p.status = 'open' and p.closed_by is distinct from 'FL25 workbook' and p.closed_by is not null then continue; end if;",
        '    perform _pay_snapshot(p);',
        "    update pay_periods set status = 'closed', closed_by = 'FL25 workbook', closed_at = now(), exported_by = 'FL25 workbook', exported_at = now(),",
        "           notes = 'Paid from the FL25 Bucking & Trimming Piece Rate workbook' where id = p.id;",
        '  end loop;',
        'end $$;',
        'commit;',
        "select task, count(*) entries, round(sum(lbs), 1) lbs, round(sum(hours), 1) hours, round(sum(pay), 2) pay from piece_pay where source = 'FL25 workbook' group by 1;"]
open('supabase/import_piece_fl25.sql', 'w').write('\n'.join(out) + '\n')
print(len(rows), 'entries,', len(crew), 'crew')
